function detectLocale() {
  const stored = localStorage.getItem("islandr.locale");
  if (stored && messages[stored]) return stored;
  const browser = (navigator.language || "en").split("-")[0];
  return messages[browser] ? browser : "en";
}

export const locale = reactive({ current: detectLocale() });

export function setLocale(lang) {
  if (!messages[lang]) return;
  locale.current = lang;
  localStorage.setItem("islandr.locale", lang);
}

// t("key") or t("key", { count: 3, name: "foo" })
export function t(key, vars) {
  const msg = (messages[locale.current] || messages.en)[key] ?? key;
  if (!vars) return msg;
  return msg.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}
