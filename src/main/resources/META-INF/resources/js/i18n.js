function detectLocale() {
  const stored = localStorage.getItem("islandr.locale");
  if (stored && messages[stored]) return stored;
  const browser = (navigator.language || "en").split("-")[0];
  return messages[browser] ? browser : "en";
}

export const locale = reactive({ current: detectLocale() });

export function setLocale(lang) {
  if (!messages[lang]) return;
  locale.current = lang;
  localStorage.setItem("islandr.locale", lang);
}

// t("key") or t("key", { count: 3, name: "foo" })
export function t(key, vars) {
  const msg = (messages[locale.current] || messages.en)[key] ?? key;
  if (!vars) return msg;
  return msg.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}

// Localised relative time ("3h ago" / "vor 3 h"). Shared by every view that
// shows a timestamp — reads locale.current through t(), so it swaps per theme.
export function relativeTime(iso) {
  if (!iso) return t("common.never");
  const s = Math.round((Date.now() - new Date(iso).getTime()) / 1000);
  if (s < 60) return t("time.rel_sec", { n: s });
  const m = Math.round(s / 60);
  if (m < 60) return t("time.rel_min", { n: m });
  const h = Math.round(m / 60);
  if (h < 24) return t("time.rel_hour", { n: h });
  return t("time.rel_day", { n: Math.round(h / 24) });
}

// Absolute timestamp for tooltips / audit — formatted in the active locale.
export function formatDate(iso) {
  return iso ? new Date(iso).toLocaleString(locale.current === "de" ? "de-DE" : "en-US") : t("common.never");
}
